def load(path: Path) -> dict:
    value = yaml.safe_load(path.read_text(encoding="utf-8"))
    if not isinstance(value, dict):
        raise ValueError(f"Invalid YAML config: {path}")
    return value


def replace_once(text: str, old: str, new: str) -> str:
    if text.count(old) != 1:
        raise ValueError(f"Expected exactly one source fragment: {old!r}")
    return text.replace(old, new, 1)


def update_training_hash(text: str) -> str:
    """Pin rendered jobs to the training source shipped in the new code bundle."""
    known_previous = (
        PRE_DIRECTIONAL_TRAIN_SHA256,
        PRE_BOOTSTRAP_TRAIN_SHA256,
        PREVIOUS_TRAIN_SHA256,
        LEGACY_TRAIN_SHA256,
    )
    previous = [value for value in known_previous if text.count(value) == 1]
    current_count = text.count(TRAIN_SHA256)
    if len(previous) == 1 and current_count == 0:
        return text.replace(previous[0], TRAIN_SHA256, 1)
    if not previous and current_count == 1:
        return text
    raise ValueError(
        "Expected exactly one known or current training-script hash, "
        f"got previous={previous} current={current_count}"
    )


