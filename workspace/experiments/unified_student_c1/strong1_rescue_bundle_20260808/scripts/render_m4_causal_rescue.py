def render_full(base: dict, branches: list[str]) -> dict:
    jobs_by_name = {str(job["name"]): job for job in base.get("jobs") or []}
    rendered = copy.deepcopy(base)
    rendered["description"] = (
        "Complete the selected C4-qualified M4 causal branch from atomic round 500 "
        "to the exact one-epoch round-3000 checkpoint"
    )
    output_jobs = []
    for branch in branches:
        spec = BRANCHES[branch]
        job = copy.deepcopy(jobs_by_name[spec["source_job"]])
        job["name"] = spec["job"]
        job["command"] = (
            cf4_rescue_command(
                str(job["command"]),
                branch,
                spec["preference_reduction"],
                spec["objective_mode"],
                spec["checkpoint_objective_mode"],
            )
            if spec["data_mode"] == "cf4_balanced"
            else dense_rescue_command(
                str(job["command"]), branch, spec["preference_reduction"], spec["objective_mode"]
            )
            if spec["repeat"] == "1.0"
            else rescue_command(
                str(job["command"]), spec["preference_reduction"], spec["objective_mode"]
            )
        )
        submit = job["submit_args"]
        submit["max_attempts"] = 2
        submit["max_run_duration_seconds"] = 345600
        submit["env"]["BRANCH"] = branch
        submit["env"]["CAUSAL_WEIGHT"] = spec["weight"]
        submit["env"]["NORMALIZE_CAUSAL"] = spec["normalize"]
        output_jobs.append(job)
    rendered["jobs"] = output_jobs
    return rendered


def render_eval(base: dict) -> dict:
    rendered = copy.deepcopy(base)
    rendered["description"] = (
        "Formal T1 T2 T3 T5 T6 and frozen C4 evaluation of the selected "
        "causal-rescue M4 checkpoint"
    )
    old = "/mnt/amulet/studentmodeling/world_model_v1/m4/selected_seed42.json"
    new = "/mnt/amulet/studentmodeling/world_model_v1/m4/causal_rescue/selected_seed42.json"
    for job in rendered.get("jobs") or []:
        command = str(job["command"])
        if command.count(old) != 1:
            raise ValueError(f"Receipt path drift in {job.get('name')}")
        job["command"] = command.replace(old, new)
    return rendered


def write(path: Path, value: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(yaml.safe_dump(value, sort_keys=False), encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--mode", choices=("full", "eval"), required=True)
    parser.add_argument("--base", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--branches", nargs="*", choices=tuple(BRANCHES))
    args = parser.parse_args()
    base = load(args.base)
    if args.mode == "full":
        branches = args.branches or list(BRANCHES)
        write(args.output, render_full(base, branches))
    else:
        if args.branches:
            raise ValueError("--branches is only valid for full mode")
        write(args.output, render_eval(base))
    print(json.dumps({"mode": args.mode, "output": str(args.output)}, sort_keys=True))


if __name__ == "__main__":
    main()
